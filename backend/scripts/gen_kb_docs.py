def generate_all():
    count = 0
    for kb_name, buckets in DISEASE_DATA.items():
        for sub, items in buckets.items():  # sub: public / private
            folder = cfg.UPLOAD_DIR / kb_name / (cfg.PUBLIC_DIR if sub == "public" else cfg.PRIVATE_DIR)
            folder.mkdir(parents=True, exist_ok=True)
            for item in items:
                name, symptoms, causes, diagnosis, manage, prevent = item
                text = (
                    f"# {name}\n\n"
                    f"> 以下为科普与就医参考信息，不构成诊断、处方或治疗建议；"
                    f"具体病情请咨询专业医生。\n\n"
                    f"## 常见症状\n" + "".join(f"- {s}\n" for s in symptoms) +
                    f"\n## 常见病因\n" + "".join(f"- {c}\n" for c in causes) +
                    f"\n## 诊断要点\n{diagnosis}。\n\n"
                    f"## 一般处理与就医建议\n{manage}；症状持续或加重请及时就诊。\n\n"
                    f"## 预防\n{prevent}。\n"
                )
                fname = f"{name}.md"
                (folder / fname).write_text(text, encoding="utf-8")
                count += 1
    print(f"[Docs] 已生成 {count} 篇知识库文档。")
    return count


if __name__ == "__main__":
    generate_all()
