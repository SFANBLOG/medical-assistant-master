def main() -> None:
    total_pub = total_pri = 0
    seen_hashes = {}
    dup = 0
    too_short = 0
    # 清空旧的生成结果，确保「重新生成」彻底
    for cat in CATEGORY_DISEASES:
        cat_dir = os.path.join(UPLOAD_ROOT, cat)
        for vis in ("公有", "私有"):
            sub = os.path.join(cat_dir, vis)
            if os.path.isdir(sub):
                shutil.rmtree(sub)
            os.makedirs(sub, exist_ok=True)

    for cat, vis_map in CATEGORY_DISEASES.items():
        cat_dir = os.path.join(UPLOAD_ROOT, cat)
        pub = vis_map.get("公有", [])
        pri = vis_map.get("私有", [])
        total_pub += len(pub)
        total_pri += len(pri)
        for vis, items in (("公有", pub), ("私有", pri)):
            sub = os.path.join(cat_dir, vis)
            for name, defi in items:
                text = build_doc(cat, name, defi, vis)
                fname = f"{name}.md"
                with open(os.path.join(sub, fname), "w", encoding="utf-8") as f:
                    f.write(text)
                # 校验
                if len(text) < 1000:
                    too_short += 1
                    print(f"[字数不足] {cat}/{vis}/{fname} ({len(text)} 字)")
                h = hashlib.md5(text.encode("utf-8")).hexdigest()
                if h in seen_hashes:
                    dup += 1
                    print(f"[重复] {cat}/{vis}/{fname} 与 {seen_hashes[h]} 内容完全相同")
                else:
                    seen_hashes[h] = f"{cat}/{vis}/{fname}"

    print(f"\n生成完成：")
    print(f"  类别数：{len(CATEGORY_DISEASES)}")
    print(f"  公有文档：{total_pub} 篇 ｜ 私有文档：{total_pri} 篇 ｜ 合计：{total_pub + total_pri} 篇")
    print(f"  字数不足(<1000)：{too_short} 篇 ｜ 完全重复：{dup} 篇")
    if too_short or dup:
        raise SystemExit("存在字数不足或重复文档，请检查数据。")


if __name__ == "__main__":
    main()
